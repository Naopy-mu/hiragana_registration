-- Run once in Supabase SQL Editor. Backend connects using the database owner.
BEGIN;
CREATE TABLE IF NOT EXISTS public.participants (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    registration_key_hash varchar(64) NOT NULL UNIQUE,
    token_hash varchar(64) NOT NULL UNIQUE,
    submission_id varchar(36) NOT NULL UNIQUE,
    consent_version varchar(100) NOT NULL,
    consent_text text NOT NULL,
    registered_at timestamptz NOT NULL DEFAULT now(),
    status varchar(20) NOT NULL DEFAULT 'registered' CHECK (status IN ('registered', 'submitted')),
    pdf_path text,
    submitted_at timestamptz,
    CHECK (status <> 'submitted' OR (pdf_path IS NOT NULL AND submitted_at IS NOT NULL))
);
CREATE TABLE IF NOT EXISTS public.pages (
    id varchar(36) PRIMARY KEY,
    submission_id varchar(36) NOT NULL REFERENCES public.participants(submission_id) ON DELETE CASCADE,
    qr_code varchar(80) NOT NULL,
    page_number integer NOT NULL CHECK (page_number > 0),
    original_name varchar(255) NOT NULL,
    original_path text NOT NULL,
    corrected_path text NOT NULL,
    metrics_json text NOT NULL,
    version varchar(36) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT uq_submission_qr UNIQUE (submission_id, qr_code)
);
CREATE INDEX IF NOT EXISTS ix_pages_submission_id ON public.pages(submission_id);
ALTER TABLE public.participants ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.pages ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.participants, public.pages FROM anon, authenticated;
REVOKE ALL ON SEQUENCE public.participants_id_seq FROM anon, authenticated;
-- No anonymous Storage policies. The app uses the server secret; bucket is private.
INSERT INTO storage.buckets (id, name, public, file_size_limit)
VALUES ('handwriting-private', 'handwriting-private', false, NULL)
ON CONFLICT (id) DO UPDATE SET public = false;
COMMIT;
